/**
 * 툴 결과를 모델에게 돌려줄 때 씌우는 포장.
 *
 * ★ 태그가 필요한 이유: read_page·find_element·list_tabs의 결과는 전부
 *   공격자가 쓸 수 있는 텍스트다(페이지 본문, 요소 라벨, 탭 제목).
 *   포장 없이 넣으면 모델에게는 우리가 쓴 지시문과 구분되지 않는다.
 *   §7의 3중 방어 중 ①에 해당한다 — 실효성은 낮지만 공짜다.
 */
export function wrapToolResult(text: string): string {
  return `<tool_result>\n${text}\n</tool_result>`;
}

/** 실패한 툴 결과. 태그를 씌우지 않는다 — 우리가 쓴 문장이기 때문이다. */
export function toolFailure(reason: string): string {
  return `도구 실행에 실패했다: ${reason}`;
}

